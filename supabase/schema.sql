-- profiles: user can read/update own
create policy "Users can view own profile" on public.profiles for select using (auth.uid() = id);
create policy "Users can update own profile" on public.profiles for update using (auth.uid() = id);

-- beans: user CRUD own
create policy "Users can view own beans" on public.beans for select using (auth.uid() = user_id);
create policy "Users can insert own beans" on public.beans for insert with check (auth.uid() = user_id);
create policy "Users can update own beans" on public.beans for update using (auth.uid() = user_id);
create policy "Users can delete own beans" on public.beans for delete using (auth.uid() = user_id);

-- tasting_tags: user CRUD own
create policy "Users can view own tags" on public.tasting_tags for select using (auth.uid() = user_id);
create policy "Users can insert own tags" on public.tasting_tags for insert with check (auth.uid() = user_id);
create policy "Users can delete own tags" on public.tasting_tags for delete using (auth.uid() = user_id);

-- Origin catalogs: authenticated users can read suggestions, but never write them.
create policy "Authenticated users can read presets" on public.origin_presets for select to authenticated using (true);
create policy "Authenticated users can read origin countries" on public.origin_countries for select to authenticated using (true);
create policy "Authenticated users can read origin regions" on public.origin_regions for select to authenticated using (true);
create policy "Authenticated users can read origin entities" on public.origin_entities for select to authenticated using (true);

-- Blend components: strictly owned by the record's user.
create policy "Users can view own blend components" on public.blend_components for select using (auth.uid() = user_id);
create policy "Users can insert own blend components" on public.blend_components for insert with check (auth.uid() = user_id);
create policy "Users can update own blend components" on public.blend_components for update using (auth.uid() = user_id);
create policy "Users can delete own blend components" on public.blend_components for delete using (auth.uid() = user_id);

-- updated_at trigger
create or replace function update_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create trigger set_beans_updated_at
  before update on public.beans
  for each row execute function update_updated_at();
